export function t(value){
  const text=String(value??"");
  if(language==="pt")return text;
  const key=text.replace(/\s+/g," ").trim();
  if(Object.hasOwn(english,key))return text.replace(text.trim(),english[key]);
  // Composite status messages contain fixed presentation fragments and measured numbers.
  let result=text;
  for(const source of fragments)if(result.includes(source))result=result.split(source).join(english[source]);
  return result;
}
